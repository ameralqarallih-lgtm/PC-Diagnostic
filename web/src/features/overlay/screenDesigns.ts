export type Look = keyof typeof LOOK;

/** A design that is one panel of tiles filling the screen. */
function tiles(
  id: string,
  name: string,
  description: string,
  size: string,
  columns: number,
  look: Look,
  text: Partial<OverlayStyle>,
  readings: (p: Pick) => (OverlayReading | false | null | undefined)[],
): ScreenDesign {
  return {
    id,
    name,
    description,
    size,
    build: (sources) => {
      const p = picker(sources);
      return [
        {
          rect: whole(size),
          panel: {
            title: null,
            layout: 'tiles',
            columns,
            readings: p.take(readings(p).filter((r): r is OverlayReading => !!r && !!r.source)),
            style: full({ ...LOOK[look], ...text }),
          },
        },
      ];
    },
  };
}

/** A design of several panels (a header, the readings, a footer…), each in its place on the screen. */
function parts(id: string, name: string, description: string, size: string, build: (p: Pick) => ScreenDesignPart[]): ScreenDesign {
  return { id, name, description, size, build: (sources: readonly OverlaySource[]) => build(picker(sources)) };
}

/** One panel of a several-panel design. */
function part(
  rect: { x: number; y: number; width: number; height: number },
  look: Look,
  text: Partial<OverlayStyle>,
  layout: OverlayPanel['layout'],
  columns: number,
  p: Pick,
  readings: (OverlayReading | false | null | undefined)[],
): ScreenDesignPart {
  return {
    rect,
    panel: { title: null, layout, columns, readings: p.take(readings.filter((r): r is OverlayReading => !!r && !!r.source)), style: full({ ...LOOK[look], ...text }) },
  };
}

// Readings used by many designs.
const cpu = (extra: Partial<OverlayReading> = {}): OverlayReading => ({ source: 'cpu.usage', label: 'CPU', warning: 85, critical: 95, ...extra });
const gpuUse = (p: Pick, extra: Partial<OverlayReading> = {}): OverlayReading => ({ source: p.gpu('usage'), label: 'GPU', warning: 97, ...extra });
const ram = (extra: Partial<OverlayReading> = {}): OverlayReading => ({ source: 'memory.usage', label: 'RAM', warning: 85, critical: 95, ...extra });
const cpuTemp = (extra: Partial<OverlayReading> = {}): OverlayReading => ({ source: 'cpu.temp', label: 'CPU temp', max: 100, warning: 85, critical: 95, ...extra });
const gpuTemp = (p: Pick, extra: Partial<OverlayReading> = {}): OverlayReading => ({ source: p.gpu('temp'), label: 'GPU temp', max: 100, warning: 80, critical: 90, ...extra });
const hotspot = (p: Pick, extra: Partial<OverlayReading> = {}): OverlayReading => ({ source: p.gpu('hotspot'), label: 'Hot spot', max: 110, warning: 95, critical: 105, ...extra });
const fps = (extra: Partial<OverlayReading> = {}): OverlayReading => ({ source: 'game.fps', label: 'FPS', max: 240, ...extra });
// VRAM as a percentage (its used/total text is too wide for a narrow tile); wide tiles ask for 'of'.
const vram = (p: Pick, extra: Partial<OverlayReading> = {}): OverlayReading => ({ source: p.gpu('vram'), label: 'VRAM', show: 'percent', ...extra });
const down = (p: Pick, extra: Partial<OverlayReading> = {}): OverlayReading => ({ source: p.net('down'), label: 'Download', ...extra });
const up = (p: Pick, extra: Partial<OverlayReading> = {}): OverlayReading => ({ source: p.net('up'), label: 'Upload', ...extra });
const ping = (extra: Partial<OverlayReading> = {}): OverlayReading => ({ source: 'net.ping.internet', label: 'Ping', warning: 80, critical: 150, ...extra });
const clock = (extra: Partial<OverlayReading> = {}): OverlayReading => ({ source: 'time.clock', ...extra });

