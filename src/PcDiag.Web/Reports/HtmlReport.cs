/// <summary>
/// Renders an incident report as one self-contained HTML file: inline CSS and SVG charts, no script and nothing
/// fetched (its own Content-Security-Policy forbids it), so it opens offline, prints well and can be sent to someone.
/// Every value from the incident is HTML-encoded. The diagnostic summary comes at the end (PROJECT §19).
/// </summary>
public static class HtmlReport
{
    private static readonly string[] Palette = ["#0284c7", "#7c3aed", "#059669", "#d97706", "#db2777", "#0d9488", "#4f46e5", "#dc2626", "#65a30d", "#9333ea", "#0891b2", "#ea580c"];

    /// <summary>The report.</summary>
    public static string Render(IncidentReport report, ReportKind kind)
    {
        ArgumentNullException.ThrowIfNull(report);
        var s = report.Detail.Summary;
        var html = new StringBuilder(64 * 1024);
        html.Append("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">")
            .Append("<meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; style-src 'unsafe-inline'; img-src data:\">")
            .Append("<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">")
            .Append("<title>").Append(E($"{s.Key} – {s.Title} ({(kind == ReportKind.Quick ? "quick report" : "technical report")})")).Append("</title><style>")
            .Append(Styles).Append("</style></head><body><main>");

        Header(html, report, kind);
        Timeline(html, report, kind);
        Charts(html, report, kind);
        Anomalies(html, report);
        if (kind == ReportKind.Technical)
        {
            Processes(html, report);
            WindowsEvents(html, report);
            Display(html, report);
            Drivers(html, report);
            SystemInformation(html, report);
        }

        Summary(html, report);
        html.Append("<footer>Generated by PC Diagnostic on ").Append(E(Local(report, report.GeneratedAt.ToUnixTimeMilliseconds(), true)))
            .Append(". Statements describe what was recorded and when; they never claim a cause. Times are local (")
            .Append(E(report.Zone.DisplayName)).Append(").</footer></main></body></html>");
        return html.ToString();
    }

    private static void Header(StringBuilder html, IncidentReport report, ReportKind kind)
    {
        var s = report.Detail.Summary;
        html.Append("<header><p class=\"kicker\">PC Diagnostic · ").Append(kind == ReportKind.Quick ? "Quick report" : "Technical report").Append("</p>")
            .Append("<h1>").Append(E(s.Title)).Append("</h1><dl class=\"facts\">");
        Fact(html, "Incident", s.Key);
        Fact(html, "When", Local(report, report.Center, true));
        Fact(html, "Reported as", s.UserType is { } type ? type.ToDisplayName() : "—");
        Fact(html, "Captured by", Source(s.Source));
        Fact(html, "State", s.State.ToString());
        Fact(html, "Severity", s.Severity.ToString());
        Fact(html, "Evidence", s.SnapshotOnly ? $"from the capture on ({s.PostSeconds} s; the recorder was not recording before)" : $"{s.PreSeconds / 60} min before and {s.PostSeconds} s after");
        html.Append("</dl>");
        if (!string.IsNullOrWhiteSpace(s.Notes))
        {
            html.Append("<p class=\"note\"><strong>Notes:</strong> ").Append(E(s.Notes)).Append("</p>");
        }

        foreach (var trigger in report.Detail.Triggers.Where(t => !string.IsNullOrWhiteSpace(t.Note) || !string.IsNullOrWhiteSpace(t.Detail)))
        {
            html.Append("<p class=\"note\">").Append(E(Local(report, trigger.Ts, false))).Append(" · ").Append(E(Source(trigger.Source))).Append(": ")
                .Append(E(trigger.Note ?? trigger.Detail ?? "")).Append("</p>");
        }

        html.Append("</header>");
    }

    private static void Timeline(StringBuilder html, IncidentReport report, ReportKind kind)
    {
        var entries = kind == ReportKind.Quick
            ? report.Timeline.Where(e => e.Importance >= 2 && Math.Abs(e.Ts - report.Center) <= 180_000).Take(40).ToList()
            : report.Timeline;
        html.Append("<section><h2>Timeline</h2>");
        if (entries.Count == 0)
        {
            html.Append("<p class=\"muted\">").Append(kind == ReportKind.Quick ? "Nothing notable was recorded in the 3 minutes around the incident." : "Nothing was recorded in the window.").Append("</p></section>");
            return;
        }

        html.Append("<table class=\"timeline\"><thead><tr><th>Time</th><th>What</th><th>Kind</th></tr></thead><tbody>");
        var marked = false;
        foreach (var e in entries)
        {
            if (!marked && e.Ts >= report.Center)
            {
                html.Append("<tr class=\"incident\"><td>").Append(E(Local(report, report.Center, false))).Append("</td><td colspan=\"2\">● Incident</td></tr>");
                marked = true;
            }

            html.Append("<tr class=\"i").Append(Math.Clamp(e.Importance, 0, 4)).Append("\"><td>").Append(E(Local(report, e.Ts, false))).Append("</td><td>")
                .Append(E(e.Title)).Append("</td><td>").Append(E(Kind(e.Kind))).Append("</td></tr>");
        }

        if (!marked)
        {
            html.Append("<tr class=\"incident\"><td>").Append(E(Local(report, report.Center, false))).Append("</td><td colspan=\"2\">● Incident</td></tr>");
        }

        html.Append("</tbody></table></section>");
    }

    private static void Charts(StringBuilder html, IncidentReport report, ReportKind kind)
    {
        var charts = kind == ReportKind.Quick ? report.Charts.Take(2).ToList() : report.Charts;
        if (charts.Count == 0)
        {
            return;
        }

        html.Append("<section><h2>Measurements</h2>");
        foreach (var chart in charts)
        {
            html.Append("<figure><figcaption>").Append(E(chart.Title)).Append("</figcaption>").Append(Svg(report, chart)).Append("<ul class=\"legend\">");
            for (var i = 0; i < chart.Series.Count; i++)
            {
                var (info, data) = chart.Series[i];
                var values = data.Points.Select(p => p[3]).ToList();
                html.Append("<li><span style=\"background:").Append(Palette[i % Palette.Length]).Append("\"></span>").Append(E(info.Label))
                    .Append(" <em>max ").Append(E(Value(values.Max(), chart.Unit))).Append("</em></li>");
            }

            html.Append("</ul></figure>");
        }

        html.Append("</section>");
    }

    private static string Svg(IncidentReport report, ReportChart chart)
    {
        const double Width = 760, Height = 170, Left = 56, Right = 8, Top = 8, Bottom = 22;
        var from = (double)report.Detail.From;
        var to = (double)Math.Max(report.Detail.To, report.Detail.From + 1000);
        var max = chart.Fixed ? 100 : Math.Max(chart.Series.SelectMany(s => s.Data.Points).Select(p => p[3]).DefaultIfEmpty(0).Max() * 1.1, 1e-9);
        double X(double t) => Left + ((t - from) / (to - from) * (Width - Left - Right));
        double Y(double v) => Top + ((1 - Math.Clamp(v / max, 0, 1)) * (Height - Top - Bottom));
        var svg = new StringBuilder();
        svg.Append(CultureInfo.InvariantCulture, $"<svg viewBox=\"0 0 {Width} {Height}\" role=\"img\" aria-label=\"{E(chart.Title)}\">");
        for (var i = 0; i <= 4; i++)
        {
            var v = max * i / 4;
            svg.Append(CultureInfo.InvariantCulture, $"<line x1=\"{Left}\" x2=\"{Width - Right}\" y1=\"{Y(v):0.#}\" y2=\"{Y(v):0.#}\" class=\"grid\"/>")
                .Append(CultureInfo.InvariantCulture, $"<text x=\"{Left - 4}\" y=\"{Y(v) + 3:0.#}\" class=\"axis\" text-anchor=\"end\">{E(Value(v, chart.Unit))}</text>");
        }

        for (var i = 0; i <= 4; i++)
        {
            var t = from + ((to - from) * i / 4);
            svg.Append(CultureInfo.InvariantCulture, $"<text x=\"{X(t):0.#}\" y=\"{Height - 6}\" class=\"axis\" text-anchor=\"{(i == 0 ? "start" : i == 4 ? "end" : "middle")}\">")
                .Append(E(Local(report, (long)t, false))).Append("</text>");
        }

        var center = X(report.Center);
        svg.Append(CultureInfo.InvariantCulture, $"<line x1=\"{center:0.#}\" x2=\"{center:0.#}\" y1=\"{Top}\" y2=\"{Height - Bottom}\" class=\"center\"/>");
        for (var i = 0; i < chart.Series.Count; i++)
        {
            var points = chart.Series[i].Data.Points;
            var line = string.Join(' ', points.Select(p => string.Create(CultureInfo.InvariantCulture, $"{X(p[0]):0.#},{Y(p[2]):0.#}")));
            svg.Append("<polyline fill=\"none\" stroke-width=\"1.4\" stroke=\"").Append(Palette[i % Palette.Length]).Append("\" points=\"").Append(line).Append("\"/>");
        }

        return svg.Append("</svg>").ToString();
    }

    private static void Anomalies(StringBuilder html, IncidentReport report)
    {
        if (report.Anomalies.Count == 0)
        {
            return;
        }

        html.Append("<section><h2>Anomalies</h2><table><thead><tr><th>From</th><th>Anomaly</th><th>Reasoning</th></tr></thead><tbody>");
        foreach (var a in report.Anomalies.OrderBy(a => a.StartedAt))
        {
            html.Append("<tr><td>").Append(E(Local(report, a.StartedAt, false))).Append("</td><td>").Append(E(a.Classification))
                .Append(a.Device is { Length: > 0 } d && !a.Series.Contains(':', StringComparison.Ordinal) ? " · " + E(d) : "")
                .Append("</td><td>").Append(E(a.Summary)).Append("</td></tr>");
        }

        html.Append("</tbody></table></section>");
    }

    private static void Processes(StringBuilder html, IncidentReport report)
    {
        var processes = report.Processes.Processes.Take(30).ToList();
        if (processes.Count == 0)
        {
            return;
        }

        // Enhanced mode measured disk and network separately.
        var trueIo = processes.Any(p => p.NetBytesPerSec is not null);
        html.Append("<section><h2>Processes at the incident</h2><p class=\"muted\">The busiest 30 at ")
            .Append(E(report.Processes.SampleTs is { } ts ? Local(report, ts, false) : "—"))
            .Append(". Every sample is in processes.csv.</p><table><thead><tr><th>Process</th><th>PID</th><th>CPU</th><th>Memory</th><th>GPU</th><th>Disk I/O</th>")
            .Append(trueIo ? "<th>Disk only</th><th>Network</th>" : "")
            .Append("<th>State</th></tr></thead><tbody>");
        foreach (var p in processes)
        {
            html.Append("<tr><td title=\"").Append(E(p.Path ?? "")).Append("\">").Append(E(p.Name)).Append(SignatureNote(p)).Append("</td><td>").Append(p.Pid).Append("</td><td>")
                .Append(E(p.CpuPercent is { } c ? Value(c, "%") : "—")).Append("</td><td>").Append(E(p.PrivateBytes is { } m ? Value(m, "B") : "—")).Append("</td><td>")
                .Append(E(p.GpuPercent is { } g ? Value(g, "%") : "—")).Append("</td><td>")
                .Append(E(Value((p.IoReadBytesPerSec ?? 0) + (p.IoWriteBytesPerSec ?? 0), "B/s"))).Append("</td><td>");
            if (trueIo)
            {
                html.Append(E(p.DiskBytesPerSec is { } d ? Value(d, "B/s") : "—")).Append("</td><td>")
                    .Append(E(p.NetBytesPerSec is { } n ? Value(n, "B/s") : "—")).Append("</td><td>");
            }

            html.Append(E(p.State)).Append("</td></tr>");
        }

        html.Append("</tbody></table></section>");
    }

    /// <summary>A short note after a process name when its program file is not signed, or not validly.</summary>
    private static string SignatureNote(ProcessAtTime process) => process.Signature switch
    {
        nameof(SignatureStatus.NotSigned) => " <span class=\"muted\">(not signed)</span>",
        nameof(SignatureStatus.NotTrusted) => " <span class=\"muted\">(signature not valid)</span>",
        _ => string.Empty,
    };

    private static void WindowsEvents(StringBuilder html, IncidentReport report)
    {
        var events = report.Timeline.Where(e => e.Kind == "windows-event").ToList();
        html.Append("<section><h2>Windows events</h2>");
        if (events.Count == 0)
        {
            html.Append("<p class=\"muted\">No classified Windows event in the window.</p></section>");
            return;
        }

        html.Append("<table><thead><tr><th>Time</th><th>Event</th><th>Source</th></tr></thead><tbody>");
        foreach (var e in events)
        {
            var source = e.Detail is { ValueKind: JsonValueKind.Object } d
                ? $"{Prop(d, "provider")} {Prop(d, "eventId")}".Trim()
                : "";
            html.Append("<tr class=\"i").Append(Math.Clamp(e.Importance, 0, 4)).Append("\"><td>").Append(E(Local(report, e.Ts, false))).Append("</td><td>").Append(E(e.Title))
                .Append("</td><td>").Append(E(source)).Append("</td></tr>");
        }

        html.Append("</tbody></table></section>");
    }

    private static void Display(StringBuilder html, IncidentReport report)
    {
        html.Append("<section><h2>Display</h2>");
        if (report.System.Display is { } display)
        {
            html.Append("<pre>").Append(E(JsonSerializer.Serialize(display, IncidentReport.Json))).Append("</pre>");
        }
        else
        {
            html.Append("<p class=\"muted\">No display configuration was recorded.</p>");
        }

        html.Append("</section>");
    }

    private static void Drivers(StringBuilder html, IncidentReport report)
    {
        if (report.System.Drivers.Count == 0)
        {
            return;
        }

        html.Append("<section><h2>Drivers</h2><table><thead><tr><th>Class</th><th>Device</th><th>Provider</th><th>Version</th><th>Date</th></tr></thead><tbody>");
        foreach (var d in report.System.Drivers)
        {
            html.Append("<tr><td>").Append(E(d.DeviceClass)).Append("</td><td>").Append(E(d.DeviceName)).Append("</td><td>").Append(E(d.Provider ?? ""))
                .Append("</td><td>").Append(E(d.Version ?? "")).Append("</td><td>").Append(E(d.Date ?? "")).Append("</td></tr>");
        }

        html.Append("</tbody></table></section>");
    }

    private static void SystemInformation(StringBuilder html, IncidentReport report)
    {
        html.Append("<section><h2>System</h2><dl class=\"facts\">");
        foreach (var (key, value) in report.System.Information.OrderBy(kv => kv.Key, StringComparer.Ordinal))
        {
            Fact(html, key, value ?? "");
        }

        html.Append("</dl>");
        var unavailable = report.System.Availability.Where(a => !string.Equals(a.Availability, "Available", StringComparison.Ordinal)).ToList();
        if (unavailable.Count > 0)
        {
            html.Append("<h3>Not recorded</h3><ul>");
            foreach (var a in unavailable.Take(40))
            {
                html.Append("<li>").Append(E(a.Series)).Append(": ").Append(E(a.Reason ?? a.Availability)).Append("</li>");
            }

            html.Append("</ul>");
        }

        html.Append("</section>");
    }

    /// <summary>The diagnostic summary (PROJECT §19), at the end: OBSERVATIONS, POSSIBLE CORRELATIONS, NOT PROVEN.</summary>
    private static void Summary(StringBuilder html, IncidentReport report)
    {
        html.Append("<section class=\"summary\"><h2>Diagnostic summary</h2>");
        if (report.Findings.Count == 0)
        {
            html.Append("<p class=\"muted\">This incident has not been analyzed yet.</p></section>");
            return;
        }

        (string Title, string[] Levels)[] sections =
        [
            ("Observations", ["ConfirmedEvent", "Observation"]),
            ("Possible correlations", ["Correlation", "PossibleExplanation"]),
            ("Not proven", ["NotProven"]),
        ];
        foreach (var (title, levels) in sections)
        {
            var items = report.Findings.Where(f => levels.Contains(f.Level)).ToList();
            if (items.Count == 0)
            {
                continue;
            }

            html.Append("<h3>").Append(E(title.ToUpperInvariant())).Append("</h3><ol>");
            foreach (var f in items)
            {
                html.Append("<li><span class=\"level\">").Append(E(Level(f.Level))).Append("</span> ").Append(E(f.Text)).Append("</li>");
            }

            html.Append("</ol>");
        }

        html.Append("</section>");
    }

    private static void Fact(StringBuilder html, string name, string value) =>
        html.Append("<div><dt>").Append(E(name)).Append("</dt><dd>").Append(E(value)).Append("</dd></div>");

    private static string Prop(JsonElement element, string name) =>
        element.TryGetProperty(name, out var value) && value.ValueKind is JsonValueKind.String or JsonValueKind.Number ? value.ToString() : "";

    private static string Level(string level) => level switch
    {
        "ConfirmedEvent" => "Confirmed event",
        "PossibleExplanation" => "Possible explanation",
        "Correlation" => "Correlation detected",
        "NotProven" => "Not proven",
        _ => level,
    };

    private static string Kind(string kind) => kind switch
    {
        "windows-event" => "Windows",
        "process" => "Process",
        "service" => "Service",
        "display" => "Display",
        "recorder" => "Recorder",
        "anomaly" => "Anomaly",
        "trigger" => "Report",
        _ => kind,
    };

    private static string Source(IncidentSource source) => source switch
    {
        IncidentSource.User => "the dashboard",
        IncidentSource.Hotkey => "the hotkey",
        IncidentSource.Tray => "the tray",
        IncidentSource.Rule => "an anomaly rule",
        IncidentSource.Event => "a Windows event rule",
        IncidentSource.BootRecovery => "the restart check",
        _ => source.ToString(),
    };

    private static string Local(IncidentReport report, long unixMs, bool withDate) =>
        TimeZoneInfo.ConvertTime(DateTimeOffset.FromUnixTimeMilliseconds(unixMs), report.Zone)
            .ToString(withDate ? "yyyy-MM-dd HH:mm:ss" : "HH:mm:ss", CultureInfo.InvariantCulture);

    /// <summary>A value with its unit, e.g. "37 %", "4.2 GB", "1.5 MB/s".</summary>
    public static string Value(double value, string unit) => unit switch
    {
        "B" => Bytes(value),
        "B/s" => Bytes(value) + "/s",
        "%" => value.ToString("0.#", CultureInfo.InvariantCulture) + " %",
        "" => value.ToString("0.##", CultureInfo.InvariantCulture),
        _ => value.ToString(Math.Abs(value) < 10 ? "0.#" : "0", CultureInfo.InvariantCulture) + " " + unit,
    };

    private static string Bytes(double bytes) => bytes switch
    {
        >= 1_073_741_824 => (bytes / 1_073_741_824).ToString("0.0", CultureInfo.InvariantCulture) + " GB",
        >= 1_048_576 => (bytes / 1_048_576).ToString("0.0", CultureInfo.InvariantCulture) + " MB",
        >= 1024 => (bytes / 1024).ToString("0", CultureInfo.InvariantCulture) + " KB",
        _ => bytes.ToString("0", CultureInfo.InvariantCulture) + " B",
    };

    private static string E(string? text) => WebUtility.HtmlEncode(text ?? "");

