using System.Globalization;
using System.Net;
using System.Text;
using PcDiag.Core.Diagnostics;
using PcDiag.Core.Events;

namespace PcDiag.Web.Reports;

/// <summary>
/// Renders a period diagnostic as one self-contained HTML file, like the incident reports: inline CSS, no script and
/// nothing fetched, so it opens offline, prints well and can be sent to someone. Every value is HTML-encoded.
/// </summary>
public static class PeriodHtmlReport
{
    /// <summary>The report.</summary>
    public static string Render(PeriodReport report, TimeZoneInfo zone)
    {
        ArgumentNullException.ThrowIfNull(report);
        ArgumentNullException.ThrowIfNull(zone);
        var html = new StringBuilder(64 * 1024);
        var title = $"Period diagnostic {Local(report.From, zone)} – {Local(report.To, zone)}";
        html.Append("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">")
            .Append("<meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; style-src 'unsafe-inline'\">")
            .Append("<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">")
            .Append("<title>").Append(E(title)).Append("</title><style>")
            .Append(HtmlReport.Styles).Append(Styles).Append("</style></head><body><main>");

        var s = report.Summary;
        html.Append("<header><p class=\"kicker\">PC Diagnostic · Period diagnostic</p><h1>")
            .Append(E($"{Local(report.From, zone)} – {Local(report.To, zone)}")).Append("</h1><dl class=\"facts\">");
        Fact(html, "Length", Minutes(s.PeriodMinutes));
        Fact(html, "Recorded", s.PeriodMinutes > 0 ? $"{Minutes(s.RecordedMinutes)} ({(100 * s.RecordedMinutes / s.PeriodMinutes).ToString("0", CultureInfo.InvariantCulture)} %)" : "—");
        Fact(html, "Findings", string.Join(", ", s.FindingsBySeverity.Where(x => x.Value > 0).Select(x => $"{x.Value} {x.Key.ToLowerInvariant()}")) is { Length: > 0 } counts ? counts : "none");
        html.Append("</dl>");
        if (s.Note is { } note)
        {
            html.Append("<p class=\"note\">").Append(E(note)).Append("</p>");
        }

        html.Append("</header><section><h2>Most important findings</h2>");
        if (s.Top.Count == 0)
        {
            html.Append("<p class=\"muted\">Nothing in this period crossed a threshold or was logged as a problem.</p>");
        }
        else
        {
            var titles = report.Sections.ToDictionary(x => x.Id, x => x.Title, StringComparer.Ordinal);
            html.Append("<ol class=\"findings\">");
            foreach (var f in s.Top)
            {
                Finding(html, f, f.Section is { } id && titles.TryGetValue(id, out var section) ? section : null);
            }

            html.Append("</ol>");
        }

        html.Append("</section>");
        foreach (var section in report.Sections)
        {
            Section(html, section);
        }

        html.Append("<footer>Generated by PC Diagnostic on ").Append(E(Local(report.GeneratedAt, zone)))
            .Append(". Statements describe what was recorded and when; they never claim a cause. Thresholds are the anomaly rules in Settings → Triggers. Times are local (")
            .Append(E(zone.DisplayName)).Append(").</footer></main></body></html>");
        return html.ToString();
    }

    private static void Section(StringBuilder html, PeriodSection section)
    {
        html.Append("<section><h2>").Append(E(section.Title)).Append("</h2>");
        if (section.Stats.Count > 0)
        {
            html.Append("<dl class=\"stats\">");
            foreach (var stat in section.Stats)
            {
                html.Append("<div><dt>").Append(E(stat.Label)).Append("</dt><dd>").Append(E(stat.Value)).Append("</dd></div>");
            }

            html.Append("</dl>");
        }

        if (section.Findings.Count == 0)
        {
            html.Append("<p class=\"muted\">Nothing stood out.</p>");
        }
        else
        {
            html.Append("<ol class=\"findings\">");
            foreach (var f in section.Findings)
            {
                Finding(html, f, null);
            }

            html.Append("</ol>");
        }

        foreach (var table in section.Tables)
        {
            html.Append("<h3>").Append(E(table.Title.ToUpperInvariant())).Append("</h3><table><thead><tr>");
            foreach (var column in table.Columns)
            {
                html.Append("<th>").Append(E(column)).Append("</th>");
            }

            html.Append("</tr></thead><tbody>");
            foreach (var row in table.Rows)
            {
                html.Append("<tr>");
                foreach (var cell in row)
                {
                    html.Append("<td>").Append(E(cell)).Append("</td>");
                }

                html.Append("</tr>");
            }

            html.Append("</tbody></table>");
        }

        html.Append("</section>");
    }

    private static void Finding(StringBuilder html, PeriodFinding f, string? section)
    {
        html.Append("<li><span class=\"sev sev-").Append(f.Severity.ToString().ToLowerInvariant()).Append("\">").Append(E(f.Severity.ToString())).Append("</span> <strong>")
            .Append(E(f.Title)).Append("</strong>");
        if (f.Occurrences > 1)
        {
            html.Append(" <span class=\"muted\">×").Append(f.Occurrences.ToString("N0", CultureInfo.InvariantCulture)).Append("</span>");
        }

        if (section is not null)
        {
            html.Append(" <span class=\"muted\">· ").Append(E(section)).Append("</span>");
        }

        html.Append("<br><span class=\"level\">").Append(E(Level(f.Level))).Append("</span> ").Append(E(f.Text)).Append("</li>");
    }

    internal static string Level(EvidenceLevel level) => level switch
    {
        EvidenceLevel.ConfirmedEvent => "Logged event",
        EvidenceLevel.PossibleExplanation => "Possible explanation",
        EvidenceLevel.Correlation => "Correlation detected",
        EvidenceLevel.NotProven => "Not proven",
        _ => "Observed",
    };

    private static string Minutes(double minutes) => minutes switch
    {
        < 90 => minutes.ToString("0", CultureInfo.InvariantCulture) + " min",
        < 2880 => $"{Math.Floor(minutes / 60).ToString("0", CultureInfo.InvariantCulture)} h {(minutes % 60).ToString("0", CultureInfo.InvariantCulture)} min",
        _ => $"{Math.Floor(minutes / 1440).ToString("0", CultureInfo.InvariantCulture)} d {Math.Floor(minutes % 1440 / 60).ToString("0", CultureInfo.InvariantCulture)} h",
    };

    private static void Fact(StringBuilder html, string name, string value) =>
        html.Append("<div><dt>").Append(E(name)).Append("</dt><dd>").Append(E(value)).Append("</dd></div>");

    private static string Local(DateTimeOffset at, TimeZoneInfo zone) =>
        TimeZoneInfo.ConvertTime(at, zone).ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture);

    private static string E(string? text) => WebUtility.HtmlEncode(text ?? "");

    private const string Styles =
        """
        .stats{display:grid;grid-template-columns:1fr;gap:3px;margin:0 0 10px}.stats div{display:flex;gap:10px}.stats dt{color:var(--muted);min-width:190px;flex-shrink:0}.stats dd{margin:0}
        .findings{padding-left:20px}.findings li{margin:7px 0;break-inside:avoid}
        .sev{display:inline-block;font-size:11px;font-weight:600;border-radius:999px;padding:0 7px;color:#fff;background:#64748b}
        .sev-critical{background:#7f1d1d}.sev-high{background:#dc2626}.sev-medium{background:#d97706}.sev-low{background:#0284c7}
        """;
}
